//Write a Dart program that declares two numeric variables and performs addition, subtraction, multiplication, division, and modulo on them. Print each result.

void main() {
  double num1 = 15.0;
  double num2 = 4.0;

  print("Addition: " + (num1 + num2).toString());
  print("Subtraction: " + (num1 - num2).toString());
  print("Multiplication: " + (num1 * num2).toString());
  print("Division: " + (num1 / num2).toString());
  print("Modulo: " + (num1 % num2).toString());
}
