//  This Dart program views basic variable declarations
//  and arithmetic operations.
//  It showcases the use of different data types and operations.
void main() {
  int a = 10;
  int b = 5;
  double c = 13.5;
  double d = 2.5;

  // Addition
  print("Addition (a + b): " + (a + b).toString());

  // Subtraction
  print("Subtraction (a - b): " + (a - b).toString());

  // Multiplication
  print("Multiplication (a * b): " + (a * b).toString());

  // Division
  print("Division (a / b): " + (a / b).toString());

  // Modulo
  print("Modulo (a % b): " + (a % b).toString());

  // Addition with doubles
  print("Addition (c + d): " + (c + d).toString());

  // Subtraction with doubles
  print("Subtraction (c - d): " + (c - d).toString());

  // Multiplication with doubles
  print("Multiplication (c * d): " + (c * d).toString());

  // Division with doubles
  print("Division (c / d): " + (c / d).toString());

  // Modulo with doubles
  print("Modulo (c % d): " + (c % d).toString());
}
